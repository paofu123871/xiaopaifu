function formatDate(d) {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return y + '-' + m + '-' + day;
}

function getTodayStr() { return formatDate(new Date()); }

function getStreakCount(checkinData, moduleId) {
  let streak = 0;
  const today = new Date();
  for (let i = 0; i < 365; i++) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const dateStr = formatDate(d);
    if (checkinData[dateStr] && checkinData[dateStr][moduleId]) {
      streak++;
    } else {
      if (i === 0) continue;
      break;
    }
  }
  return streak;
}

function getTotalCount(checkinData, moduleId) {
  let count = 0;
  Object.values(checkinData).forEach(function(day) {
    if (day[moduleId]) count++;
  });
  return count;
}
